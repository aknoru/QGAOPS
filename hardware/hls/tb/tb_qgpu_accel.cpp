/* ----------------------------------------------------------------------- */
/* Test 1: Zero array add/sub */
static void test_zero_addvec(void)
{
    fix16_t A[8] = {0,0,0,0,0,0,0,0};
    fix16_t B[8] = {0,0,0,0,0,0,0,0};
    fix16_t C[8], D[8];
    run_addvec(A, B, C, D, 8);
    int pass = 1;
    for (int i = 0; i < 8; i++) {
        if (C[i] != 0 || D[i] != 0) { pass = 0; break; }
    }
    report("Zero array add/sub", pass);
}

/* ----------------------------------------------------------------------- */
/* Test 2: Normal array add/sub N=8 */
static void test_normal_addvec(void)
{
    /* A = [0.25, 0.5, -0.25, -0.5, 0.125, -0.125, 0.75, -0.75] in Q1.14 */
    fix16_t A[8] = {
        float_to_fix16(0.25f),
        float_to_fix16(0.5f),
        float_to_fix16(-0.25f),
        float_to_fix16(-0.5f),
        float_to_fix16(0.125f),
        float_to_fix16(-0.125f),
        float_to_fix16(0.75f),
        float_to_fix16(-0.75f)
    };
    /* B = [0.25, 0.25, 0.25, 0.25, 0.25, 0.25, 0.25, 0.25] */
    fix16_t B[8];
    for (int i = 0; i < 8; i++) B[i] = float_to_fix16(0.25f);

    fix16_t C[8], D[8];
    run_addvec(A, B, C, D, 8);

    int pass = 1;
    for (int i = 0; i < 8; i++) {
        fix16_t exp_c = fix16_add(A[i], B[i]);
        fix16_t exp_d = fix16_sub(A[i], B[i]);
        if (C[i] != exp_c || D[i] != exp_d) {
            printf("    Mismatch i=%d: C[%d]=%d (exp %d), D[%d]=%d (exp %d)\n",
                   i, i, C[i], exp_c, i, D[i], exp_d);
            pass = 0;
        }
    }
    report("Normal array add/sub N=8", pass);
}

