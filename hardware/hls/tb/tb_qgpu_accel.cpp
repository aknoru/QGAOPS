static int g_pass = 0;
static int g_fail = 0;

static void report(const char* name, int pass)
{
    if (pass) {
        printf("  [PASS] %s\n", name);
        g_pass++;
    } else {
        printf("  [FAIL] %s\n", name);
        g_fail++;
    }
}

/* Convert Q1.14 fixed-point to float for comparison */
static float fix16_to_float(fix16_t v)
{
    return (float)v / (float)FIX16_SCALE;
}

/* Convert float to Q1.14 fixed-point (saturating) */
static fix16_t float_to_fix16(float f)
{
    int32_t raw = (int32_t)(f * FIX16_SCALE);
    if (raw > FIX16_MAX) raw = FIX16_MAX;
    if (raw < FIX16_MIN) raw = FIX16_MIN;
    return (fix16_t)raw;
}

/* Helper to construct AXI4-Stream packet */
static stream_word_t make_word(ap_uint<32> val, ap_uint<1> last = 0)
{
    stream_word_t w;
    w.data = val;
    w.keep = 0xF;
    w.strb = 0xF;
    w.last = last;
    return w;
}

/* Build a complete stream transaction and invoke qgpu_accel() */
static void run_addvec(
    const fix16_t* A,
    const fix16_t* B,
    fix16_t* C_out,
    fix16_t* D_out,
    uint32_t N
)
{
    hls::stream<stream_word_t> in_s, out_s;

    /* Header */
    in_s.write(make_word(OPCODE_ADDVEC));
    in_s.write(make_word(N));

    /* Array A — packed as 32-bit pairs */
    for (uint32_t i = 0; i < N; i += 2) {
        ap_uint<32> d = (uint16_t)A[i];
        if (i+1 < N) d |= ((ap_uint<32>)(uint16_t)A[i+1]) << 16;
        in_s.write(make_word(d, 0));
    }
    /* Array B */
    for (uint32_t i = 0; i < N; i += 2) {
        ap_uint<32> d = (uint16_t)B[i];
        if (i+1 < N) d |= ((ap_uint<32>)(uint16_t)B[i+1]) << 16;
        bool is_last = (i + 2 >= N);
        in_s.write(make_word(d, is_last ? 1 : 0));
    }

    volatile uint32_t status = 0, op_count = 0;
    qgpu_accel(in_s, out_s, &status, &op_count);

    /* Read C = A+B */
    for (uint32_t i = 0; i < N; i += 2) {
        stream_word_t w = out_s.read();
        C_out[i] = (fix16_t)(int16_t)(w.data & 0xFFFF);
        if (i+1 < N) C_out[i+1] = (fix16_t)(int16_t)((w.data >> 16) & 0xFFFF);
    }
    /* Read D = A-B */
    for (uint32_t i = 0; i < N; i += 2) {
        stream_word_t w = out_s.read();
        D_out[i] = (fix16_t)(int16_t)(w.data & 0xFFFF);
        if (i+1 < N) D_out[i+1] = (fix16_t)(int16_t)((w.data >> 16) & 0xFFFF);
    }
}

static void run_gp(
    uint32_t       opcode,
    const G3_mv    A,
    const G3_mv    B,
    G3_mv          result
)
{
    hls::stream<stream_word_t> in_s, out_s;

    /* Header */
    in_s.write(make_word(opcode));
    in_s.write(make_word(G3_DIM));

    /* MV A — 8 int16 packed as 4 × 32-bit words */
    for (int i = 0; i < G3_DIM; i += 2) {
        ap_uint<32> d = (uint16_t)A[i];
        if (i+1 < G3_DIM) d |= ((ap_uint<32>)(uint16_t)A[i+1]) << 16;
        in_s.write(make_word(d, 0));
    }
    /* MV B */
    for (int i = 0; i < G3_DIM; i += 2) {
        ap_uint<32> d = (uint16_t)B[i];
        if (i+1 < G3_DIM) d |= ((ap_uint<32>)(uint16_t)B[i+1]) << 16;
        bool is_last = (i + 2 >= G3_DIM);
        in_s.write(make_word(d, is_last ? 1 : 0));
    }

    volatile uint32_t status = 0, op_count = 0;
    qgpu_accel(in_s, out_s, &status, &op_count);

    /* Read 8 int16 result — 4 × 32-bit words */
    for (int i = 0; i < G3_DIM; i += 2) {
        stream_word_t w = out_s.read();
        result[i] = (fix16_t)(int16_t)(w.data & 0xFFFF);
        if (i+1 < G3_DIM) result[i+1] = (fix16_t)(int16_t)((w.data >> 16) & 0xFFFF);
    }
}

