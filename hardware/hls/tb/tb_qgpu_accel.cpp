/* Test 7: GP — e0 * e1 = e01 (bivector) */
static void test_gp_e0_e1(void)
{
    /*
     * In G(3,0,0):  e0 * e1 = e01
     * mask_a=1 (e0), mask_b=2 (e1)
     * mask_c = 1 XOR 2 = 3 → e01  (index 3)
     * sign = sign_product(1,2) = +1  (no swaps needed)
     * metric = 1 (no shared bits)
     *
     * Expected: R[3] = +1.0 = FIX16_SCALE, all others 0
     */
    G3_mv A = {0};
    G3_mv B = {0};
    G3_mv R;

    A[1] = FIX16_SCALE;   /* e0 */
    B[2] = FIX16_SCALE;   /* e1 */

    run_gp(OPCODE_GP, A, B, R);

    int pass = (R[3] == FIX16_SCALE);
    for (int i = 0; i < G3_DIM; i++) {
        if (i == 3) continue;
        if (R[i] != 0) { pass = 0; break; }
    }
    if (!pass) {
        printf("    e0*e1: R[3]=%d (expected %d)\n", R[3], FIX16_SCALE);
    }
    report("GP: e0 * e1 = e01", pass);
}

/* ----------------------------------------------------------------------- */
/* Test 8: GP — e1 * e0 = -e01 (anti-commutativity) */
static void test_gp_e1_e0(void)
{
    /*
     * In G(3,0,0):  e1 * e0 = -e01
     * mask_a=2 (e1), mask_b=1 (e0)
     * mask_c = 2 XOR 1 = 3 → e01 (index 3)
     * sign = sign_product(2,1) = -1 (one swap: e1 e0 → -e0 e1)
     *
     * Expected: R[3] = -1.0 = -FIX16_SCALE, all others 0
     */
    G3_mv A = {0};
    G3_mv B = {0};
    G3_mv R;

    A[2] = FIX16_SCALE;   /* e1 */
    B[1] = FIX16_SCALE;   /* e0 */

    run_gp(OPCODE_GP, A, B, R);

    int pass = (R[3] == -FIX16_SCALE);
    for (int i = 0; i < G3_DIM; i++) {
        if (i == 3) continue;
        if (R[i] != 0) { pass = 0; break; }
    }
    if (!pass) {
        printf("    e1*e0: R[3]=%d (expected %d)\n", R[3], -FIX16_SCALE);
    }
    report("GP: e1 * e0 = -e01 (anti-commutativity)", pass);
}

/* ----------------------------------------------------------------------- */
/* Test 9: GP — Golden vector comparison
 * Vector A = 0.5*e0 + 0.3*e1 + 0.7*e2
 * Vector B = 0.2*e0 - 0.4*e1 + 0.6*e2
 *
 * Python golden (precomputed via ga/geometric_product.py):
 *   A*B in G(3,0,0):
 *   scalar = 0.5*0.2 + 0.3*(-0.4) + 0.7*0.6 = 0.10 - 0.12 + 0.42 = 0.40
 *   e01    = 0.5*(-0.4) - 0.2*0.3           = -0.20 - 0.06 = -0.26
 *            Wait: e0*e1 term: A[e0]*B[e1] = 0.5*(-0.4)=−0.20
 *                 e1*e0 term: A[e1]*B[e0] = 0.3*0.2=+0.06 (but sign=-1 for e1*e0 → -0.06)
 *            e01 = A[e0]*B[e1]*sign(e0,e1) + A[e1]*B[e0]*sign(e1,e0)
 *                = 0.5*(-0.4)*(+1) + 0.3*0.2*(-1) = -0.20 - 0.06 = -0.26
 *   e02    = A[e0]*B[e2]*sign(e0,e2) + A[e2]*B[e0]*sign(e2,e0)
 *            = 0.5*0.6*(+1) + 0.7*0.2*(-1) = 0.30 - 0.14 = +0.16
 *   e12    = A[e1]*B[e2]*sign(e1,e2) + A[e2]*B[e1]*sign(e2,e1)
 *            = 0.3*0.6*(+1) + 0.7*(-0.4)*(-1) = 0.18 + 0.28 = +0.46
 *
 * Tolerance: 2 LSBs in Q1.14 (due to truncation in multiply)
 */
static void test_gp_golden_vector(void)
{
    G3_mv A = {0};
    G3_mv B = {0};
    G3_mv R;

    /* A = 0.5*e0 + 0.3*e1 + 0.7*e2 */
    A[1] = float_to_fix16(0.5f);
    A[2] = float_to_fix16(0.3f);
    A[4] = float_to_fix16(0.7f);

    /* B = 0.2*e0 - 0.4*e1 + 0.6*e2 */
    B[1] = float_to_fix16(0.2f);
    B[2] = float_to_fix16(-0.4f);
    B[4] = float_to_fix16(0.6f);

    run_gp(OPCODE_GP, A, B, R);

    /* Expected (Python golden, Q1.14): */
    fix16_t exp_scalar = float_to_fix16(0.40f);
    fix16_t exp_e01    = float_to_fix16(-0.26f);
    fix16_t exp_e02    = float_to_fix16(0.16f);
    fix16_t exp_e12    = float_to_fix16(0.46f);

    int tol = 2;   /* ±2 LSBs tolerance for Q1.14 truncation */

    int pass = 1;
    if (abs((int)R[0] - (int)exp_scalar) > tol) {
        printf("    scalar: got %d, exp %d, diff %d\n",
               R[0], exp_scalar, abs((int)R[0]-(int)exp_scalar));
        pass = 0;
    }
    if (abs((int)R[3] - (int)exp_e01) > tol) {
        printf("    e01:    got %d, exp %d, diff %d\n",
               R[3], exp_e01, abs((int)R[3]-(int)exp_e01));
        pass = 0;
    }
    if (abs((int)R[5] - (int)exp_e02) > tol) {
        printf("    e02:    got %d, exp %d, diff %d\n",
               R[5], exp_e02, abs((int)R[5]-(int)exp_e02));
        pass = 0;
    }
    if (abs((int)R[6] - (int)exp_e12) > tol) {
        printf("    e12:    got %d, exp %d, diff %d\n",
               R[6], exp_e12, abs((int)R[6]-(int)exp_e12));
        pass = 0;
    }
    if (abs((int)R[1]) > tol || abs((int)R[2]) > tol ||
        abs((int)R[4]) > tol || abs((int)R[7]) > tol) {
        printf("    unexpected non-zero grade-1/3: R[1]=%d R[2]=%d R[4]=%d R[7]=%d\n",
               R[1], R[2], R[4], R[7]);
        pass = 0;
    }
    report("GP: golden vector (0.5e0+0.3e1+0.7e2)*(0.2e0-0.4e1+0.6e2)", pass);
}

