/* Test 6: GP — e0 * e0 = scalar (+1.0 in G3) */
static void test_gp_e0_e0(void)
{
    /*
     * In G(3,0,0):  e0 * e0 = +1 (scalar)
     * Multivector e0:  coeffs[1] = 1.0, all others = 0
     * Expected result: scalar = 1.0, coeffs[0] = 1.0 (=16384 in Q1.14)
     *
     * Reference: ga/basis.py::sign_product(1,1) = +1
     *            metric.py: metric_coefficient(1,1) = +1
     *            mask_c = 1 XOR 1 = 0 → scalar blade
     */
    G3_mv A = {0};
    G3_mv B = {0};
    G3_mv R;

    A[1] = FIX16_SCALE;   /* e0 = 1.0 */
    B[1] = FIX16_SCALE;   /* e0 = 1.0 */

    run_gp(OPCODE_GP, A, B, R);

    /* Expected: R[0]=FIX16_SCALE (scalar=1.0), R[1..7]=0 */
    int pass = (R[0] == FIX16_SCALE);
    for (int i = 1; i < G3_DIM; i++) {
        if (R[i] != 0) { pass = 0; break; }
    }
    if (!pass) {
        printf("    e0*e0: scalar=%d (expected %d)\n", R[0], FIX16_SCALE);
    }
    report("GP: e0 * e0 = scalar +1", pass);
}

