/* Test 10: Outer product — e0 ^ e1 = e01 */
static void test_wedge_e0_e1(void)
{
    G3_mv A = {0};
    G3_mv B = {0};
    G3_mv R;

    A[1] = FIX16_SCALE;   /* e0 */
    B[2] = FIX16_SCALE;   /* e1 */

    run_gp(OPCODE_WEDGE, A, B, R);

    /* e0 ^ e1 = e01, same as GP for grade-1 (no overlap) */
    int pass = (R[3] == FIX16_SCALE);
    for (int i = 0; i < G3_DIM; i++) {
        if (i == 3) continue;
        if (R[i] != 0) { pass = 0; break; }
    }
    report("WEDGE: e0 ^ e1 = e01", pass);
}

