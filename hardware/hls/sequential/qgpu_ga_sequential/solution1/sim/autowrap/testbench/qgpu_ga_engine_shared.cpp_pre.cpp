static void compute_gp_shared(
    const int32_t a[8],
    const int32_t b[8],
    int32_t c[8],
    uint32_t opcode,
    bool *overflow
) {

    accum_t accum[8];

    for (int k = 0; k < 8; k++) {
        accum[k] = 0;
    }


    SHARED_OUTER_LOOP:
    for (int left = 0; left < 8; left++) {
        uint8_t left_mask = BASIS_MASKS[left];
        uint8_t left_grade = BASIS_GRADES[left];
        int32_t a_val = a[left];

        SHARED_INNER_LOOP:
        for (int right = 0; right < 8; right++) {

            uint8_t right_mask = BASIS_MASKS[right];
            uint8_t right_grade = BASIS_GRADES[right];
            int32_t b_val = b[right];

            bool include_term = true;
            if (opcode == 0x02) {

                if ((left_mask & right_mask) != 0) {
                    include_term = false;
                }
            } else if (opcode == 0x03) {

                uint8_t out_mask = left_mask ^ right_mask;
                int out_grade = BASIS_GRADES[mask_to_index(out_mask)];
                if (left_grade > right_grade || out_grade != (right_grade - left_grade)) {
                    include_term = false;
                }
            }

            if (include_term) {
                int out_idx = mask_to_index(left_mask ^ right_mask);
                int sign = blade_product_sign(left_mask, right_mask);
                prod_t p = (prod_t)a_val * (prod_t)b_val;
                if (sign < 0) {
                    accum[out_idx] -= (accum_t)p;
                } else {
                    accum[out_idx] += (accum_t)p;
                }
            }
        }
    }


    RESCALE_LOOP:
    for (int k = 0; k < 8; k++) {
        c[k] = rescale_and_saturate(accum[k], overflow);
    }
}

void qgpu_ga_engine_shared(
    const int32_t a[8],
    const int32_t b[8],
    int32_t c[8],
    uint32_t opcode,
    uint32_t *status
) {

    bool overflow = false;
    uint32_t err_code = 0x00;

    switch (opcode) {
        case 0x04: {
            for (int k = 0; k < 8; k++) {
                c[k] = sat_add_q16(a[k], b[k], &overflow);
            }
            break;
        }

        case 0x05: {
            for (int k = 0; k < 8; k++) {
                c[k] = sat_sub_q16(a[k], b[k], &overflow);
            }
            break;
        }

        case 0x01:
        case 0x02:
        case 0x03: {
            compute_gp_shared(a, b, c, opcode, &overflow);
            break;
        }

        case 0x06: {

            int32_t scalar_val = b[0];
            for (int k = 0; k < 8; k++) {
                prod_t p = (prod_t)a[k] * (prod_t)scalar_val;
                c[k] = rescale_and_saturate((accum_t)p, &overflow);
            }
            break;
        }

        case 0x07: {

            int target_grade = (b[0] >= 0 && b[0] <= 3) ? b[0] : (b[0] >> 16);
            if (target_grade < 0 || target_grade > 3) {
                err_code = 0x01;
                for (int k = 0; k < 8; k++) {
                    c[k] = 0;
                }
            } else {
                for (int k = 0; k < 8; k++) {
                    c[k] = (BASIS_GRADES[k] == target_grade) ? a[k] : 0;
                }
            }
            break;
        }

        case 0x08: {

            for (int k = 0; k < 8; k++) {
                if (BASIS_GRADES[k] == 2 || BASIS_GRADES[k] == 3) {
                    c[k] = sat_sub_q16(0, a[k], &overflow);
                } else {
                    c[k] = a[k];
                }
            }
            break;
        }

        case 0x09: {

            for (int k = 0; k < 8; k++) {
                if (BASIS_GRADES[k] == 1 || BASIS_GRADES[k] == 3) {
                    c[k] = sat_sub_q16(0, a[k], &overflow);
                } else {
                    c[k] = a[k];
                }
            }
            break;
        }

        case 0x0A: {

            for (int k = 0; k < 8; k++) {
                if (BASIS_GRADES[k] == 1 || BASIS_GRADES[k] == 2) {
                    c[k] = sat_sub_q16(0, a[k], &overflow);
                } else {
                    c[k] = a[k];
                }
            }
            break;
        }

        case 0x0B: {

            int32_t t[8];
            int32_t a_rev[8];


            compute_gp_shared(a, b, t, 0x01, &overflow);


            for (int k = 0; k < 8; k++) {
                if (BASIS_GRADES[k] == 2 || BASIS_GRADES[k] == 3) {
                    a_rev[k] = sat_sub_q16(0, a[k], &overflow);
                } else {
                    a_rev[k] = a[k];
                }
            }


            compute_gp_shared(t, a_rev, c, 0x01, &overflow);
            break;
        }

        case 0x0C: {

            accum_t norm_accum = 0;
            for (int k = 0; k < 8; k++) {
                prod_t p = (prod_t)a[k] * (prod_t)a[k];
                norm_accum += (accum_t)p;
            }
            c[0] = rescale_and_saturate(norm_accum, &overflow);
            for (int k = 1; k < 8; k++) {
                c[k] = 0;
            }
            break;
        }

        default: {
            err_code = 0x01;
            for (int k = 0; k < 8; k++) {
                c[k] = 0;
            }
            break;
        }
    }

    *status = err_code | (overflow ? 0x04 : 0x00);
}
